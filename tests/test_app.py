import copy

import pytest
from fastapi.testclient import TestClient

from src import app as app_module


ACTIVITY_NAME = "Art Club"


@pytest.fixture
def client(monkeypatch):
    monkeypatch.setattr(app_module, "activities", copy.deepcopy(app_module.activities))
    with TestClient(app_module.app) as test_client:
        yield test_client


def test_get_activities_returns_activity_details(client):
    # Arrange
    expected_fields = {"description", "schedule", "max_participants", "participants"}

    # Act
    response = client.get("/activities")

    # Assert
    assert response.status_code == 200
    activity = response.json()[ACTIVITY_NAME]
    assert set(activity) == expected_fields
    assert activity["participants"] == []


def test_signup_adds_participant(client):
    # Arrange
    email = "new.student@mergington.edu"

    # Act
    response = client.post(
        f"/activities/{ACTIVITY_NAME}/signup",
        params={"email": email},
    )

    # Assert
    assert response.status_code == 200
    assert response.json() == {"message": f"Signed up {email} for {ACTIVITY_NAME}"}
    assert client.get("/activities").json()[ACTIVITY_NAME]["participants"] == [email]


def test_signup_rejects_duplicate_participant(client):
    # Arrange
    email = "existing.student@mergington.edu"
    app_module.activities[ACTIVITY_NAME]["participants"].append(email)

    # Act
    response = client.post(
        f"/activities/{ACTIVITY_NAME}/signup",
        params={"email": email},
    )

    # Assert
    assert response.status_code == 400
    assert response.json()["detail"] == "Student is already signed up"
    assert client.get("/activities").json()[ACTIVITY_NAME]["participants"] == [email]


def test_signup_rejects_unknown_activity(client):
    # Arrange
    email = "new.student@mergington.edu"

    # Act
    response = client.post(
        "/activities/Unknown Club/signup",
        params={"email": email},
    )

    # Assert
    assert response.status_code == 404
    assert response.json()["detail"] == "Activity not found"


def test_unregister_removes_participant(client):
    # Arrange
    email = "registered.student@mergington.edu"
    app_module.activities[ACTIVITY_NAME]["participants"].append(email)

    # Act
    response = client.delete(
        f"/activities/{ACTIVITY_NAME}/signup",
        params={"email": email},
    )

    # Assert
    assert response.status_code == 200
    assert response.json() == {"message": f"Removed {email} from {ACTIVITY_NAME}"}
    assert client.get("/activities").json()[ACTIVITY_NAME]["participants"] == []


